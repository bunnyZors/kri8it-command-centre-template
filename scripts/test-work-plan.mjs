import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { buildWorkPlan, localInstant, localDate, priorityCandidates } from "../lib/work-plan.mjs";
const policy = JSON.parse(readFileSync(new URL("../config/planning-policy.json", import.meta.url)));
const now = Date.parse("2026-10-14T07:30:00Z");
const t = (id, extra = {}) => ({ id, title:id, status:"inbox", priority:"medium", position:0, dueAt:null, extra });
const source = { status:"success",checkedAt:now,windowStart:"2026-10-14T00:00:00+01:00",windowEnd:"2026-10-22T00:00:00+01:00" };
const calendar = events => ({ sources:{ calendar:source },events });
const event = (start,end,busy=true,allDay=false) => ({ id:start,title:"Fixture",start,end,busy,allDay });
assert.equal(new Date(localInstant("2026-10-14",540)).toISOString(),"2026-10-14T08:00:00.000Z");
assert.equal(new Date(localInstant("2026-10-26",540)).toISOString(),"2026-10-26T09:00:00.000Z");
assert.equal(new Date(localInstant("2027-03-29",540)).toISOString(),"2027-03-29T08:00:00.000Z");
let plan = buildWorkPlan([t("one"),t("two")],calendar([event("2026-10-14T09:00:00+01:00","2026-10-14T10:00:00+01:00")]),policy,now);
assert.equal(plan.blocks[0].start,"2026-10-14T09:10:00.000Z");
assert.equal(plan.blocks[1].start,"2026-10-14T09:45:00.000Z");
assert.equal(plan.blocks[0].calendarAction,"none");
plan = buildWorkPlan([t("one")],calendar([event("2026-10-14T00:00:00","2026-10-15T00:00:00",false,true)]),policy,now);
assert.equal(plan.blocks[0].start,"2026-10-14T08:00:00.000Z");
plan = buildWorkPlan([t("one")],calendar([event("2026-10-14","2026-10-15",true,true)]),policy,now);
assert.equal(localDate(Date.parse(plan.blocks[0].start)),"2026-10-15");
const after = Date.parse("2026-10-16T17:30:00+01:00");
plan = buildWorkPlan([t("one")],{ sources:{ calendar:{...source,checkedAt:after} },events:[] },policy,after);
assert.equal(plan.blocks[0].start,"2026-10-19T08:00:00.000Z");
assert.equal(buildWorkPlan([t("one")],calendar([]),policy,now+19*3600000).blocks.length,0);
assert.ok(buildWorkPlan([t("one")],{sources:{calendar:{status:"success",checkedAt:now}},events:[]},policy,now).warning);
assert.equal(buildWorkPlan([t("one")],{sources:{calendar:{...source,status:"error"}},events:[]},policy,now).blocks.length,0);
assert.equal(buildWorkPlan([t("one")],{sources:{calendar:{...source,windowEnd:"2026-10-14T09:15:00+01:00"}},events:[]},policy,now).unplaced.length,1);
assert.equal(buildWorkPlan([{...t("done"),status:"done"},{...t("waiting"),status:"waiting"},t("uncertain",{confidence:"needs_confirmation"})],calendar([]),policy,now).blocks.length,0);
plan=buildWorkPlan([t("large",{durationMinutes:120})],calendar([]),policy,now);
assert.equal(plan.blocks[0].minutes,90); assert.equal(plan.blocks[0].remainingMinutes,30);
const pinned=t("pin",{focusDate:"2026-10-14"});
assert.equal(priorityCandidates([{...t("high"),priority:"high"},pinned],now)[0].id,"pin");
const rules=[{ client:"Important",aliases:["Child brand"],rank:1,confidence:"confirmed",scope:"client",sourceRef:"the owner's explicit answer" }];
assert.equal(priorityCandidates([t("ordinary"),t("important",{project:"Important"})],now,rules)[0].id,"important");
assert.equal(priorityCandidates([t("ordinary"),t("important",{project:"Important"})],now,[{...rules[0],confidence:"proposed"}])[0].id,"ordinary");
assert.equal(priorityCandidates([t("ordinary"),t("brand",{project:"Child brand"})],now,rules)[0].id,"brand");
assert.equal(buildWorkPlan(Array.from({length:8},(_,i)=>t(`${i}`)),calendar([]),policy,now).blocks.length,3);
